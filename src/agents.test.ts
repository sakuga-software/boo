import assert from 'node:assert/strict';
import { test } from 'node:test';
import { detectAgent, type AgentSignals } from './agents.js';

const signals = (patch: Partial<AgentSignals>): AgentSignals => ({
  author: 'Mheaus',
  branch: 'mathieu/feature',
  body: '',
  commitMessage: 'feat: a change',
  commitAuthors: ['Mheaus'],
  ...patch,
});

test('a pull request that a person writes alone names no agent', () => {
  assert.equal(detectAgent(signals({})), undefined);
});

test('a Claude co-author, a claude commit author or the Claude Code footer names Claude Code', () => {
  const trailer = signals({ commitMessage: 'fix: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>' });
  assert.equal(detectAgent(trailer)?.id, 'claude');
  assert.equal(detectAgent(signals({ commitAuthors: ['Mheaus', 'claude'] }))?.id, 'claude');
  assert.equal(
    detectAgent(signals({ body: '🤖 Generated with [Claude Code](https://claude.com/claude-code)' }))?.id,
    'claude',
  );
  assert.equal(detectAgent(signals({ commitMessage: 'feat: claude support' })), undefined);
});

test('the description of a cloud session gives its page', () => {
  const agent = detectAgent(
    signals({ body: '---\n_Generated by [Claude Code](https://claude.ai/code/session_01XTBFrs9KD9RTDR9UVRHbJX)_' }),
  );
  assert.deepEqual(agent, {
    id: 'claude',
    name: 'Claude Code',
    cloudSession: 'https://claude.ai/code/session_01XTBFrs9KD9RTDR9UVRHbJX',
  });
});

test('the author or the branch names the other agents', () => {
  assert.equal(detectAgent(signals({ author: 'Copilot' }))?.id, 'copilot');
  assert.equal(detectAgent(signals({ branch: 'codex/fix-login' }))?.id, 'codex');
  assert.equal(detectAgent(signals({ author: 'cursor[bot]' }))?.id, 'cursor');
  assert.equal(detectAgent(signals({ author: 'devin-ai-integration[bot]' }))?.id, 'devin');
});
